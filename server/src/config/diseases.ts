export function diseaseNameMy(disease: string): string {
  return DISEASE_NAME_MY[disease] || disease;
}

/** Prompt-friendly crop → problems summary for the vision model. */
export function cropProblemsPromptBlock(): string {
  return CROP_TYPES.map((crop) => {
    const diseases = CROP_DISEASES[crop].join(', ');
    const pests = CROP_PESTS[crop].join(', ');
    return `- ${crop} (${CROP_NAME_MY[crop]}): diseases [${diseases}]; pests [${pests}]`;
  }).join('\n');
}
