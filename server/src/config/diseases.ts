/** Flat allowlist for AI detect (unique) + Healthy. */
function uniqueLabels(lists: readonly (readonly string[])[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const list of lists) {
    for (const item of list) {
      if (!seen.has(item)) {
        seen.add(item);
        out.push(item);
      }
    }
  }
  return out;
}

export const ALL_DETECT_LABELS = [
  ...uniqueLabels([...Object.values(CROP_DISEASES), ...Object.values(CROP_PESTS)]),
  'Healthy',
] as const;

export type DetectLabel = (typeof ALL_DETECT_LABELS)[number];

/** Labels allowed for a given crop (plus Healthy). */
export function labelsForCrop(crop: string): string[] {
  const key = crop as CropType;
  if (!CROP_DISEASES[key]) return [...ALL_DETECT_LABELS];
  return [...CROP_DISEASES[key], ...CROP_PESTS[key], 'Healthy'];
}

